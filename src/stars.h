// Starting positions of the 200 background stars, copied from 1030:0C7E of
// the unpacked TSBDEMO1 image. Demo::initStars() (0DDB in the original) reads
// them once; after that the stars move on their own.
//
// Each record is a word and two bytes, and only says where a star starts:
//
//     plane  = word & 3          which of the 4 pixels of a VRAM byte
//     row    = word % 400        one of the 400 lines of the mode
//     column = (b1 ^ b2) % 80    which VRAM byte of the row (4 pixels each)
//
// Rows 0..256 land in VRAM from address 0, the part the lower half of the
// screen shows. Rows 257..399 are moved 0x142 rows on, into the memory behind
// the upper half, and 10 bytes (40 pixels) to the right, for reasons only Tran
// knew. With the registers as they are at start-up, that spreads the stars
// over the whole screen.
//
// Colour and speed are not in the record: they come from the star's place in
// the table, as Demo::moveStars() groups them (all move right):
//
//       0..79    colour FBh, 1 pixel every other tick
//      80..139   colour FCh, 1 pixel per tick
//     140..179   colour FDh, 2 pixels per tick
//     180..199   colour FEh, 4 pixels per tick
//
// The values look random; the comment on each one is what initStars() makes
// of it.
